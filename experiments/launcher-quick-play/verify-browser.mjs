// Run after scripts/play-local.mjs --browser --no-open. Uses the same browser runtime as web smoke.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const require = createRequire(path.join(root, 'web/package.json'));
const { chromium } = require('playwright-core');
const arg = name => { const i = process.argv.indexOf(name); return i < 0 ? null : process.argv[i + 1]; };
const origin = arg('--url') ?? 'http://127.0.0.1:7778';
const output = path.resolve(arg('--output') ?? path.join(here, 'output'));
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : 'chrome', args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.addInitScript(() => Object.defineProperty(navigator, 'getGamepads', { value: () => [] }));
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const result = {};
try {
  await page.route('**/play-catalog.json', route => route.fulfill({ json: { enabled: true, repository: 'arianna-arpg/hollow-wake-mmo', branch: 'main', commit: '1234567890', branches: ['main', 'codex/launcher-quick-play'] } }));
  await page.goto(`${origin}/?branch=codex%2Flauncher-quick-play`);
  await page.locator('.play-ribbon').waitFor();
  assert.equal(await page.locator('.play-branch-link').getAttribute('href'), 'https://codespaces.new/arianna-arpg/hollow-wake-mmo/tree/codex%2Flauncher-quick-play?quickstart=1');
  await page.screenshot({ path: path.join(output, 'browser-branch-picker.png') });
  await page.setViewportSize({ width: 700, height: 700 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(output, 'browser-branch-picker-narrow.png') });
  result.branchLinks = 'Selected branch and resumable Codespace link agree; narrow layout fits';
  await page.unroute('**/play-catalog.json');
  await page.setViewportSize({ width: 1280, height: 900 });
  const account = `quickplay-${Date.now()}`;
  const url = `${origin}/?play=1&account=${account}&fresh-settings`;
  await page.goto(url);
  await page.locator('.entry-scene').waitFor();
  assert.equal(await page.evaluate(() => window.hollowWake.inWorld), false);
  await page.click('[data-vessel="calling:holdfast"]');
  await page.fill('.entry-card input', 'Quickplay');
  await page.locator('.entry-card button').first().click();
  await page.waitForFunction(() => window.hollowWake?.inWorld === true, null, { timeout: 30000 });
  result.firstRun = 'Play opens Mu; Name and Wake creates and enters the selected character';
  const start = performance.now();
  // Model a login completing in a background window without touching OS focus.
  await page.addInitScript(() => { window.quickPlayBackground = true; document.hasFocus = () => !window.quickPlayBackground; });
  await page.reload();
  await page.locator('.entry-roster button[data-vessel^="character:"]').waitFor();
  assert.equal(await page.evaluate(() => window.hollowWake.inWorld), false);
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('data-vessel')?.startsWith('character:')), true);
  const before = await page.evaluate(() => ({ x: window.hollowWake.entry.x, y: window.hollowWake.entry.y }));
  await page.keyboard.down('KeyD'); await page.waitForTimeout(250); await page.keyboard.up('KeyD');
  assert.deepEqual(await page.evaluate(() => ({ x: window.hollowWake.entry.x, y: window.hollowWake.entry.y })), before);
  assert.equal(await page.evaluate(() => window.hollowWake.entry.opened), -1);
  await page.evaluate(() => { window.quickPlayBackground = false; });
  await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Wake', exact: true }).waitFor();
  await page.keyboard.press('Enter');
  result.backgroundLogin = 'Remembered vessel gets DOM focus during background login; movement stays paused; Enter works after activation without a click';
  await page.waitForFunction(() => window.hollowWake?.inWorld === true && !window.hollowWake.loading.active, null, { timeout: 30000 });
  result.remembered = 'Reload focuses the remembered vessel and waits for explicit Wake';
  result.resumeMilliseconds = Math.round(performance.now() - start);
  await page.screenshot({ path: path.join(output, 'browser-resumed.png') });
  assert.deepEqual(errors, []);
  result.pageErrors = errors;
  writeFileSync(path.join(output, 'browser-results.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
